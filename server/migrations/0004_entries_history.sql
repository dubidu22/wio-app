-- Schema v1 (plan 003, D-47 to D-57). Never edit after merge; add a new file (D-55).

-- One QR code or one manual entry (D-1), with its place and target place (D-9).
-- A place is a site and room, then optionally a fixture slot or a floor point.
CREATE TABLE entries (
  id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  workspace_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  customer_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NULL,
  code VARCHAR(255) CHARACTER SET utf8mb4 COLLATE utf8mb4_bin NULL,
  title VARCHAR(200) NULL,
  site_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NULL,
  room_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NULL,
  fixture_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NULL,
  level SMALLINT UNSIGNED NULL,
  compartment SMALLINT UNSIGNED NULL,
  floor_x_cm INT NULL,
  floor_y_cm INT NULL,
  target_site_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NULL,
  target_room_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NULL,
  target_fixture_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NULL,
  target_level SMALLINT UNSIGNED NULL,
  target_compartment SMALLINT UNSIGNED NULL,
  target_floor_x_cm INT NULL,
  target_floor_y_cm INT NULL,
  created_at DATETIME(3) NOT NULL,
  created_by CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NULL,
  updated_at DATETIME(3) NOT NULL,
  updated_by CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NULL,
  revision BIGINT UNSIGNED NOT NULL,
  deleted_at DATETIME(3) NULL,
  alive TINYINT UNSIGNED AS (IF(deleted_at IS NULL, 1, NULL)) STORED,
  PRIMARY KEY (id),
  UNIQUE KEY uq_entries_scope (workspace_id, id),
  UNIQUE KEY uq_entries_customer_scope (workspace_id, customer_id, id),
  UNIQUE KEY uq_entries_code (workspace_id, code, alive),
  KEY ix_entries_revision (workspace_id, revision),
  CONSTRAINT fk_entries_workspace FOREIGN KEY (workspace_id) REFERENCES workspaces (id),
  CONSTRAINT fk_entries_customer FOREIGN KEY (workspace_id, customer_id) REFERENCES customers (workspace_id, id),
  CONSTRAINT fk_entries_site FOREIGN KEY (workspace_id, site_id) REFERENCES sites (workspace_id, id),
  CONSTRAINT fk_entries_room FOREIGN KEY (workspace_id, site_id, room_id) REFERENCES rooms (workspace_id, site_id, id),
  CONSTRAINT fk_entries_fixture FOREIGN KEY (workspace_id, room_id, fixture_id) REFERENCES fixtures (workspace_id, room_id, id),
  CONSTRAINT fk_entries_site_customer FOREIGN KEY (workspace_id, customer_id, site_id) REFERENCES sites (workspace_id, customer_id, id),
  CONSTRAINT fk_entries_target_site FOREIGN KEY (workspace_id, target_site_id) REFERENCES sites (workspace_id, id),
  CONSTRAINT fk_entries_target_room FOREIGN KEY (workspace_id, target_site_id, target_room_id) REFERENCES rooms (workspace_id, site_id, id),
  CONSTRAINT fk_entries_target_fixture FOREIGN KEY (workspace_id, target_room_id, target_fixture_id) REFERENCES fixtures (workspace_id, room_id, id),
  CONSTRAINT fk_entries_target_site_customer FOREIGN KEY (workspace_id, customer_id, target_site_id) REFERENCES sites (workspace_id, customer_id, id),
  CONSTRAINT ck_entries_site_room CHECK ((site_id IS NULL) = (room_id IS NULL)),
  CONSTRAINT ck_entries_fixture_room CHECK (fixture_id IS NULL OR room_id IS NOT NULL),
  CONSTRAINT ck_entries_slot_fixture CHECK ((level IS NULL AND compartment IS NULL) OR fixture_id IS NOT NULL),
  CONSTRAINT ck_entries_slot_from_one CHECK ((level IS NULL OR level >= 1) AND (compartment IS NULL OR compartment >= 1)),
  CONSTRAINT ck_entries_floor_pair CHECK ((floor_x_cm IS NULL) = (floor_y_cm IS NULL)),
  CONSTRAINT ck_entries_floor_or_fixture CHECK (floor_x_cm IS NULL OR (fixture_id IS NULL AND room_id IS NOT NULL)),
  CONSTRAINT ck_entries_target_site_room CHECK ((target_site_id IS NULL) = (target_room_id IS NULL)),
  CONSTRAINT ck_entries_target_fixture_room CHECK (target_fixture_id IS NULL OR target_room_id IS NOT NULL),
  CONSTRAINT ck_entries_target_slot_fixture CHECK ((target_level IS NULL AND target_compartment IS NULL) OR target_fixture_id IS NOT NULL),
  CONSTRAINT ck_entries_target_slot_from_one CHECK ((target_level IS NULL OR target_level >= 1) AND (target_compartment IS NULL OR target_compartment >= 1)),
  CONSTRAINT ck_entries_target_floor_pair CHECK ((target_floor_x_cm IS NULL) = (target_floor_y_cm IS NULL)),
  CONSTRAINT ck_entries_target_floor_or_fixture CHECK (target_floor_x_cm IS NULL OR (target_fixture_id IS NULL AND target_room_id IS NOT NULL)),
  CONSTRAINT ck_entries_id CHECK (id REGEXP '^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$')
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_520_ci;

-- Append-only (D-54): one row per change of an entry's place, written in the same transaction.
-- from_* is a copy of the old place and has no foreign keys.
CREATE TABLE place_history (
  id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  workspace_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  customer_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NULL,
  entry_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  from_site_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NULL,
  from_room_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NULL,
  from_fixture_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NULL,
  from_level SMALLINT UNSIGNED NULL,
  from_compartment SMALLINT UNSIGNED NULL,
  from_floor_x_cm INT NULL,
  from_floor_y_cm INT NULL,
  to_site_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NULL,
  to_room_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NULL,
  to_fixture_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NULL,
  to_level SMALLINT UNSIGNED NULL,
  to_compartment SMALLINT UNSIGNED NULL,
  to_floor_x_cm INT NULL,
  to_floor_y_cm INT NULL,
  moved_at DATETIME(3) NOT NULL,
  moved_by CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NULL,
  created_at DATETIME(3) NOT NULL,
  created_by CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NULL,
  updated_at DATETIME(3) NOT NULL,
  updated_by CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NULL,
  revision BIGINT UNSIGNED NOT NULL,
  deleted_at DATETIME(3) NULL,
  PRIMARY KEY (id),
  UNIQUE KEY uq_place_history_scope (workspace_id, id),
  UNIQUE KEY uq_place_history_customer_scope (workspace_id, customer_id, id),
  KEY ix_place_history_revision (workspace_id, revision),
  CONSTRAINT fk_place_history_workspace FOREIGN KEY (workspace_id) REFERENCES workspaces (id),
  CONSTRAINT fk_place_history_customer FOREIGN KEY (workspace_id, customer_id) REFERENCES customers (workspace_id, id),
  CONSTRAINT fk_place_history_entry FOREIGN KEY (workspace_id, entry_id) REFERENCES entries (workspace_id, id),
  CONSTRAINT fk_place_history_entry_customer FOREIGN KEY (workspace_id, customer_id, entry_id) REFERENCES entries (workspace_id, customer_id, id),
  CONSTRAINT fk_place_history_moved_by FOREIGN KEY (workspace_id, moved_by) REFERENCES users (workspace_id, id),
  CONSTRAINT fk_place_history_to_site FOREIGN KEY (workspace_id, to_site_id) REFERENCES sites (workspace_id, id),
  CONSTRAINT fk_place_history_to_room FOREIGN KEY (workspace_id, to_site_id, to_room_id) REFERENCES rooms (workspace_id, site_id, id),
  CONSTRAINT fk_place_history_to_fixture FOREIGN KEY (workspace_id, to_room_id, to_fixture_id) REFERENCES fixtures (workspace_id, room_id, id),
  CONSTRAINT fk_place_history_to_site_customer FOREIGN KEY (workspace_id, customer_id, to_site_id) REFERENCES sites (workspace_id, customer_id, id),
  CONSTRAINT ck_place_history_to_site_room CHECK ((to_site_id IS NULL) = (to_room_id IS NULL)),
  CONSTRAINT ck_place_history_to_fixture_room CHECK (to_fixture_id IS NULL OR to_room_id IS NOT NULL),
  CONSTRAINT ck_place_history_to_slot_fixture CHECK ((to_level IS NULL AND to_compartment IS NULL) OR to_fixture_id IS NOT NULL),
  CONSTRAINT ck_place_history_to_slot_from_one CHECK ((to_level IS NULL OR to_level >= 1) AND (to_compartment IS NULL OR to_compartment >= 1)),
  CONSTRAINT ck_place_history_to_floor_pair CHECK ((to_floor_x_cm IS NULL) = (to_floor_y_cm IS NULL)),
  CONSTRAINT ck_place_history_to_floor_or_fixture CHECK (to_floor_x_cm IS NULL OR (to_fixture_id IS NULL AND to_room_id IS NOT NULL)),
  CONSTRAINT ck_place_history_id CHECK (id REGEXP '^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$')
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_520_ci;
