-- Any picture (D-7). The file is addressed by its SHA-256; taken_at is device time, information only.
CREATE TABLE pictures (
  id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  workspace_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  customer_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NULL,
  file_sha256 CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  file_bytes INT UNSIGNED NOT NULL,
  file_mime VARCHAR(100) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  width_px INT UNSIGNED NOT NULL,
  height_px INT UNSIGNED NOT NULL,
  taken_at DATETIME(3) NULL,
  room_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NULL,
  entry_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NULL,
  after_of CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NULL,
  created_at DATETIME(3) NOT NULL,
  created_by CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NULL,
  updated_at DATETIME(3) NOT NULL,
  updated_by CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NULL,
  revision BIGINT UNSIGNED NOT NULL,
  deleted_at DATETIME(3) NULL,
  PRIMARY KEY (id),
  UNIQUE KEY uq_pictures_scope (workspace_id, id),
  UNIQUE KEY uq_pictures_customer_scope (workspace_id, customer_id, id),
  KEY ix_pictures_revision (workspace_id, revision),
  CONSTRAINT fk_pictures_workspace FOREIGN KEY (workspace_id) REFERENCES workspaces (id),
  CONSTRAINT fk_pictures_customer FOREIGN KEY (workspace_id, customer_id) REFERENCES customers (workspace_id, id),
  CONSTRAINT fk_pictures_room FOREIGN KEY (workspace_id, room_id) REFERENCES rooms (workspace_id, id),
  CONSTRAINT fk_pictures_room_customer FOREIGN KEY (workspace_id, customer_id, room_id) REFERENCES rooms (workspace_id, customer_id, id),
  CONSTRAINT fk_pictures_entry FOREIGN KEY (workspace_id, entry_id) REFERENCES entries (workspace_id, id),
  CONSTRAINT fk_pictures_entry_customer FOREIGN KEY (workspace_id, customer_id, entry_id) REFERENCES entries (workspace_id, customer_id, id),
  CONSTRAINT fk_pictures_after_of FOREIGN KEY (workspace_id, after_of) REFERENCES pictures (workspace_id, id),
  CONSTRAINT fk_pictures_after_of_customer FOREIGN KEY (workspace_id, customer_id, after_of) REFERENCES pictures (workspace_id, customer_id, id),
  CONSTRAINT ck_pictures_file_sha256 CHECK (file_sha256 REGEXP '^[0-9a-f]{64}$'),
  CONSTRAINT ck_pictures_not_after_itself CHECK (after_of IS NULL OR after_of <> id),
  CONSTRAINT ck_pictures_id CHECK (id REGEXP '^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$')
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_520_ci;

-- Text and/or voice about an entry, room, picture, job or customer (D-3, D-50).
CREATE TABLE notes (
  id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  workspace_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  customer_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NULL,
  subject_type VARCHAR(16) NOT NULL,
  subject_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  text TEXT NULL,
  audio_sha256 CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NULL,
  audio_bytes INT UNSIGNED NULL,
  audio_seconds INT UNSIGNED NULL,
  transcript TEXT NULL,
  transcript_source VARCHAR(16) NULL,
  created_at DATETIME(3) NOT NULL,
  created_by CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NULL,
  updated_at DATETIME(3) NOT NULL,
  updated_by CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NULL,
  revision BIGINT UNSIGNED NOT NULL,
  deleted_at DATETIME(3) NULL,
  PRIMARY KEY (id),
  UNIQUE KEY uq_notes_scope (workspace_id, id),
  UNIQUE KEY uq_notes_customer_scope (workspace_id, customer_id, id),
  KEY ix_notes_revision (workspace_id, revision),
  CONSTRAINT fk_notes_workspace FOREIGN KEY (workspace_id) REFERENCES workspaces (id),
  CONSTRAINT fk_notes_customer FOREIGN KEY (workspace_id, customer_id) REFERENCES customers (workspace_id, id),
  KEY ix_notes_subject (workspace_id, subject_type, subject_id),
  CONSTRAINT ck_notes_subject_type CHECK (subject_type IN ('entry', 'room', 'picture', 'job', 'customer')),
  CONSTRAINT ck_notes_text_or_audio CHECK (text IS NOT NULL OR audio_sha256 IS NOT NULL),
  CONSTRAINT ck_notes_audio_sha256 CHECK (audio_sha256 IS NULL OR audio_sha256 REGEXP '^[0-9a-f]{64}$'),
  CONSTRAINT ck_notes_audio_bytes CHECK ((audio_sha256 IS NULL) = (audio_bytes IS NULL)),
  CONSTRAINT ck_notes_transcript_source CHECK ((transcript IS NULL) = (transcript_source IS NULL) AND (transcript_source IS NULL OR transcript_source IN ('device', 'manual'))),
  CONSTRAINT ck_notes_id CHECK (id REGEXP '^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$')
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_520_ci;
