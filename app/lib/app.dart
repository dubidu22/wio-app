/// Font bundled with the app (D-40); no platform loads fonts from a CDN.
const String wioFontFamily = 'Roboto';

/// Localisation delegates. The list generated by gen-l10n still names the
/// framework's deprecated Material localisations, which do not reach widgets
/// from package:material_ui, so the app takes material_ui's own list
/// (Cupertino, Material and Widgets).
const List<LocalizationsDelegate<Object?>> wioLocalizationsDelegates =
    <LocalizationsDelegate<Object?>>[
      AppLocalizations.delegate,
      ...GlobalMaterialLocalizations.delegates,
    ];

/// Smallest touch target (UX rule 3).
const Size wioMinTapTarget = Size(56, 56);

/// The app's theme. Text uses the bundled font so screens and goldens match;
/// every button is at least 56 x 56 (UX rule 3).
ThemeData wioTheme() {
  final buttonStyle = ButtonStyle(
    minimumSize: const WidgetStatePropertyAll<Size>(wioMinTapTarget),
    textStyle: const WidgetStatePropertyAll<TextStyle>(
      TextStyle(
        fontFamily: wioFontFamily,
        fontSize: 18,
        fontWeight: FontWeight.w500,
      ),
    ),
  );
  return ThemeData(
    colorSchemeSeed: const Color(0xFF2E5E4E),
    fontFamily: wioFontFamily,
    textButtonTheme: TextButtonThemeData(style: buttonStyle),
    outlinedButtonTheme: OutlinedButtonThemeData(style: buttonStyle),
    filledButtonTheme: FilledButtonThemeData(style: buttonStyle),
  );
}

/// Root widget. German is the first and, for now, only locale (D-23).
/// Needs a ProviderScope above it (see main.dart).
///
/// At start nothing waits for the network (D-129): the job list shows local
/// data at once, getMe checks a stored token in the background, and a fresh
/// install with no local data and no session opens "Anmelden" (D-130).
class WioApp extends ConsumerStatefulWidget {
  const WioApp({super.key, this.initialLocation = '/'});

  /// Where the app opens; tests start on other screens.
  final String initialLocation;

  @override
  ConsumerState<WioApp> createState() => _WioAppState();
}

class _WioAppState extends ConsumerState<WioApp> {
  late final GoRouter _router = buildRouter(
    initialLocation: widget.initialLocation,
  );
  late final AppLifecycleListener _lifecycle;

  @override
  void initState() {
    super.initState();
    _lifecycle = AppLifecycleListener(
      onResume: () {
        unawaited(ref.read(sessionProvider.notifier).checkIfStale());
        ref.read(syncProvider.notifier).resumed();
      },
      // Leaving the app hands sync to the phone's background work (D-376).
      onPause: () => unawaited(ref.read(backgroundSyncProvider).left()),
    );
    ref.read(backgroundSyncProvider).start();
    // The update notice opens once, from whatever screen is showing, when
    // the server first says the app is too old (D-154).
    ref.listenManual(appTooOldProvider, (previous, next) {
      if (previous == null && next != null) _router.go(updateLocation);
    });
    // Sync starts after a sign-in too, not only at start-up (D-201).
    ref.listenManual(sessionProvider, (previous, next) {
      if (previous case AsyncData(value: null) when next.value != null) {
        ref.read(syncProvider.notifier).trigger();
      }
    });
    unawaited(_start());
  }

  Future<void> _start() async {
    // Camera shots left by an earlier run go at start, never uploaded
    // (D-268).
    if (ref.read(canTakePicturesProvider)) {
      unawaited(
        ref.read(captureQueueProvider).sweep().catchError((Object _) {}),
      );
    }
    // Copies of discarded uploads go at start (D-215).
    unawaited(
      sweepUploads(
        ref.read(databaseProvider),
        ref.read(uploadStoreProvider),
      ).catchError((Object _) {}),
    );
    try {
      final session = await ref.read(sessionProvider.future);
      if (!mounted) return;
      if (session != null) {
        await ref.read(sessionProvider.notifier).check();
        // Sync starts once getMe has run (D-129, D-201).
        if (mounted) ref.read(syncProvider.notifier).trigger();
      } else if (widget.initialLocation == '/' &&
          await isLocalDatabaseEmpty(ref.read(databaseProvider)) &&
          mounted) {
        _router.go(signInLocation);
      }
    } on Object {
      // The job list shows a database error itself (D-65).
    }
  }

  @override
  void dispose() {
    _lifecycle.dispose();
    _router.dispose();
    super.dispose();
  }

  @override
  Widget build(BuildContext context) {
    return MaterialApp.router(
      debugShowCheckedModeBanner: false,
      onGenerateTitle: (context) => AppLocalizations.of(context).appTitle,
      locale: const Locale('de'),
      localizationsDelegates: wioLocalizationsDelegates,
      supportedLocales: AppLocalizations.supportedLocales,
      theme: wioTheme(),
      routerConfig: _router,
    );
  }
}
